-- Core tables: who the learner is, what they did, and what the server derived from it.
--
-- Everything lives in a private `app` schema. Supabase publishes the `public` schema through
-- its Data API, so tables there could be read or written with the app's public key,
-- skipping the API's rules. Only the API's own database role can reach `app`.
create schema app;
revoke all on schema app from public;

-- One row per learner. `id` is the Supabase Auth user id (the JWT `sub`), so anonymous
-- guests keep the same row when they upgrade to a full account.
create table app.users (
  id            uuid primary key,
  learning_lang text check (learning_lang ~ '^[a-z]{2}$'),
  daily_goal_xp integer not null default 60 check (daily_goal_xp in (30, 60, 100)),
  -- IANA zone, e.g. America/Los_Angeles. Decides where a learner's day (and streak) rolls over.
  timezone      text not null default 'UTC' check (length(timezone) between 1 and 64),
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

-- Append-only log of what learners did. Clients send events; the server derives XP,
-- streaks and review schedules from them, so no client can just claim a score.
create table app.events (
  user_id     uuid not null references app.users (id) on delete cascade,
  -- Generated by the client, so an event retried after a dropped connection counts once.
  id          uuid not null,
  kind        text not null check (kind ~ '^[a-z_]{1,40}$'),
  clip_id     text not null check (length(clip_id) between 1 and 64),
  payload     jsonb not null default '{}' check (pg_column_size(payload) <= 4096),
  -- The client's clock: used for display only, never trusted for scoring.
  occurred_at timestamptz not null,
  received_at timestamptz not null default now(),
  xp_awarded  integer not null default 0 check (xp_awarded between 0 and 100),
  primary key (user_id, id)
);
create index events_user_received_idx on app.events (user_id, received_at);

-- Spaced-repetition state per learner and clip, computed by the server from events.
create table app.cards (
  user_id       uuid not null references app.users (id) on delete cascade,
  clip_id       text not null check (length(clip_id) between 1 and 64),
  due_at        timestamptz not null,
  interval_days real not null default 0 check (interval_days >= 0),
  ease          real not null default 2.5 check (ease between 1.3 and 3.0),
  reps          integer not null default 0 check (reps >= 0),
  lapses        integer not null default 0 check (lapses >= 0),
  updated_at    timestamptz not null default now(),
  primary key (user_id, clip_id)
);
create index cards_user_due_idx on app.cards (user_id, due_at);

-- XP per learner per local day. Streaks are runs of consecutive days that hit the goal.
create table app.daily_progress (
  user_id  uuid not null references app.users (id) on delete cascade,
  day      date not null,
  xp       integer not null default 0 check (xp >= 0),
  goal_hit boolean not null default false,
  primary key (user_id, day)
);

-- Defence in depth: with RLS on and no policies, any role other than the owning API role
-- sees no rows even if it is later granted access to the schema by mistake.
alter table app.users enable row level security;
alter table app.events enable row level security;
alter table app.cards enable row level security;
alter table app.daily_progress enable row level security;
